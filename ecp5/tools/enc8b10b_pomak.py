"""enc8b10b_pomak.py — kodira TS2 (8b/10b, abcdei fghj, LSB prvi na liniji) i za svaki pomak bitova 0..19 dekodira
pomaknuti niz; ispisuje pomak koji daje opaženo preslikavanje (TASK-6160, analiza snimke E6c)."""
D5 = {0:('100111','011000'),1:('011101','100010'),2:('101101','010010'),3:('110001','110001'),4:('110101','001010'),
 5:('101001','101001'),6:('011001','011001'),7:('111000','000111'),8:('111001','000110'),9:('100101','100101'),
 10:('010101','010101'),11:('110100','110100'),12:('001101','001101'),13:('101100','101100'),14:('011100','011100'),
 15:('010111','101000'),16:('011011','100100'),17:('100011','100011'),18:('010011','010011'),19:('110010','110010'),
 20:('001011','001011'),21:('101010','101010'),22:('011010','011010'),23:('111010','000101'),24:('110011','001100'),
 25:('100110','100110'),26:('010110','010110'),27:('110110','001001'),28:('001110','001110'),29:('101110','010001'),
 30:('011110','100001'),31:('101011','010100')}
D3 = {0:('1011','0100'),1:('1001','1001'),2:('0101','0101'),3:('1100','0011'),4:('1101','0010'),5:('1010','1010'),
 6:('0110','0110'),7:('1110','0001')}
K28 = {0:('001111','110000')}; K3 = {5:('1010','0101'),7:('1000','0111')}  # K28.5, K23.7 se gradi posebno
def enc(b, k, rd):  # rd: 0 = RD-, 1 = RD+
    if k and b == 0xBC: c = ('0011111010', '1100000101')[rd]
    elif k and b == 0xF7: c = ('1110101000', '0001010111')[rd]
    else:
        x, y = b & 31, b >> 5
        s6 = D5[x][rd]; r1 = rd if s6.count('1') == 3 else 1 - rd
        if y == 7 and ((r1 == 0 and x in (17, 18, 20)) or (r1 == 1 and x in (11, 13, 14))): s4 = ('0111', '1000')[r1]
        else: s4 = D3[y][r1]
        c = s6 + s4
    ones = c.count('1'); nrd = rd if ones == 5 else (1 if ones > 5 else 0)
    if ones == 5 and c[:6].count('1') != 3: nrd = rd  # balansiran ukupno
    return c, nrd
dec = {}
for b in range(256):
    for rd in (0, 1):
        c, _ = enc(b, 0, rd); dec.setdefault(c, '%02x' % b)
for rd in (0, 1):
    dec[enc(0xBC, 1, rd)[0]] = 'COM'; dec[enc(0xF7, 1, rd)[0]] = 'PAD'
ts2 = [(0xBC, 1), (0xF7, 1), (0xF7, 1), (0x80, 0), (0x02, 0), (0x00, 0)] + [(0x45, 0)] * 10
bits, rd = '', 0
for _ in range(6):
    for b, k in ts2:
        c, rd = enc(b, k, rd); bits += c
for sh in range(1, 10):
    s = bits[160 + sh:160 + sh + 160]
    print(sh, ' '.join(dec.get(s[i:i + 10], '?') for i in range(0, 160, 10)))
